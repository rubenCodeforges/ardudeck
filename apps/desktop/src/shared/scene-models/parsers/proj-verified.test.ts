function metres(lat: number, lon: number, p: number[]): number {
  const r = Math.PI / 180, R = 6371000;
  return Math.hypot((p[0]! - lon) * r * R * Math.cos(lat * r), (p[1]! - lat) * r * R);
}

describe('PROJ-verified CRS definitions', () => {
  it.each(TRUTH)('EPSG:%i inverts cs2cs output to within a metre', (code, lat, lon, a, b) => {
    const def = PROJ_VERIFIED[code]!;
    // cs2cs prints in the CRS's own axis order; some EPSG codes are northing first.
    const err = Math.min(metres(lat, lon, proj4(def, 'EPSG:4326', [a, b])), metres(lat, lon, proj4(def, 'EPSG:4326', [b, a])));
    expect(err).toBeLessThan(1);
  });
});
